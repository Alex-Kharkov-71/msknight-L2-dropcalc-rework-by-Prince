-- Class tree for L2 High Five (the old game DB had a class_list table, L2JMobius does not).
-- DropCalc reads class names (and the parent class) from this table.
-- NOTE: the names carry a race prefix exactly like the old class_list did:
-- H_ human, E_ elf, DE_ dark elf, O_ orc, D_ dwarf, K_ kamael - pages use it
-- to work out the race and strip it for display.
-- Written from the standard High Five class tree - if your datapack differs,
-- send data/stats/players/classList.xml and an importer can fill it instead.
-- Run in the GAME database.
